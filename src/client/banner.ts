const GLYPH_DENSITY = new Map<string, number>([
  [" ", 0],
  ["░", 1],
  ["▒", 2],
  ["▓", 3],
  ["█", 4],
]);

function compactBrainAscii(source: string): string {
  const lines = source.split("\n");
  const width = Math.max(...lines.map((line) => line.length));
  const compact: string[] = [];
  for (let row = 0; row < lines.length; row += 2) {
    let output = "";
    for (let column = 0; column < width; column += 2) {
      let glyph = " ";
      let density = 0;
      for (let y = 0; y < 2; y += 1) {
        for (let x = 0; x < 2; x += 1) {
          const candidate = lines[row + y]?.[column + x] ?? " ";
          const candidateDensity = GLYPH_DENSITY.get(candidate) ?? 0;
          if (candidateDensity > density) {
            glyph = candidate;
            density = candidateDensity;
          }
        }
      }
      output += glyph;
    }
    compact.push(output.trimEnd());
  }
  return compact.join("\n").trimEnd();
}

export const LITHIUM_BRAIN_ASCII_COMPACT = compactBrainAscii(LITHIUM_BRAIN_ASCII);

const GREEN = "\u001b[38;2;108;255;156m";
const SOFT = "\u001b[38;2;217;255;232m";
const DIM = "\u001b[38;2;115;146;125m";
const RESET = "\u001b[0m";

export function renderLithiumClientBanner(color = false): string {
  const art = color ? `${GREEN}${LITHIUM_BRAIN_ASCII_COMPACT}${RESET}` : LITHIUM_BRAIN_ASCII_COMPACT;
  const title = color
    ? `${SOFT}LITHIUM AI${RESET} ${DIM}// CLIENT · LOCAL EXECUTION NODE${RESET}`
    : "LITHIUM AI // CLIENT · LOCAL EXECUTION NODE";
  return `\n${art}\n\n${title}`;
}

export function printLithiumClientBanner(options: { color?: boolean } = {}): void {
  const color = options.color ?? Boolean(process.stdout.isTTY && !Bun.env.NO_COLOR);
  console.log(renderLithiumClientBanner(color));
}
